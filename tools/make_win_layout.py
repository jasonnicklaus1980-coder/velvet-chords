#!/usr/bin/env python3
"""Writes src/win_layout.h: the Windows editor's controls, one row per control on each of the six pages.

The source is the MPC skin's TUI.json (package/skin), so the Windows window uses the same positions, names and
parameter bindings as the MPC screen. Run it after the skin changes:  python3 tools/make_win_layout.py
"""
import json, re, sys, os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SKIN = os.path.join(ROOT, "package", "skin", "Velvet Chords - VST - Velvet Chords", "TUI.json")
OUT = os.path.join(ROOT, "src", "win_layout.h")
PAGE_W, PAGE_H = 1280, 628

def main():
    tui = json.load(open(SKIN))["pageData"]
    defs = {d["key"]: d["value"] for d in tui["componentDefinitions"]["localComponentDefinitions"]}
    pages = []
    for tab in tui["tabs"]:
        comp = tab["componentName"]                       # e.g. "PLAY|Play"
        page_name = tab["tabName"]
        controls = []
        for x in defs[comp]["componentsData"]:
            cd = x["componentData"]
            ty = cd["type"]
            if ty == "Image":
                continue
            binds = [m["value"] for m in x["handle remapping"]["map"] if m["key"] == "Data"]
            m = re.match(r"Parameter (\d+)$", binds[0]) if binds else None
            if not m:
                continue
            bx, by, bw, bh = (int(v) for v in x["bounds"]["bounds"].split())
            if bx < 0 or by < 0 or bx + bw > PAGE_W or by + bh > PAGE_H:
                sys.exit("control outside the page: %s %s" % (page_name, cd["name"]))
            if ty.startswith("vcSeg_"):
                kind, seg = "SEG", int(ty.rsplit("_", 1)[1])
            elif ty.startswith(("vcPad", "vcKey", "vcDot")):
                kind, seg = "SHOW", -1                     # pads, keys and scale dots: shown, not clicked
            else:
                kind, seg = "CTL", -1                      # fields, arrows, banks, switches, buttons
            controls.append((bx, by, bw, bh, int(m.group(1)), seg, kind, cd["name"]))
        pages.append((page_name, controls))

    lines = [
        "/* Generated by tools/make_win_layout.py from package/skin TUI.json. Do not edit by hand. */",
        "#ifndef VC_WIN_LAYOUT_H",
        "#define VC_WIN_LAYOUT_H",
        "",
        "/* kind: CTL = click steps or triggers the parameter, SEG = click sets the segment's value, SHOW = display only */",
        "typedef enum { WIN_CTL_CTL, WIN_CTL_SEG, WIN_CTL_SHOW } WinKind;",
        "typedef struct { unsigned char page; short x, y, w, h; short param; short seg; unsigned char kind; const char *name; } WinCtl;",
        "#define WIN_PAGE_W %d" % PAGE_W,
        "#define WIN_PAGE_H %d" % PAGE_H,
        "#define WIN_PAGE_COUNT %d" % len(pages),
        "static const char *const WIN_PAGE_NAMES[WIN_PAGE_COUNT] = {%s};" % ", ".join('"%s"' % p[0] for p in pages),
        "static const WinCtl WIN_CTL[] = {",
    ]
    total = 0
    for pi, (name, controls) in enumerate(pages):
        lines.append("    /* %s: %d controls */" % (name, len(controls)))
        for (bx, by, bw, bh, param, seg, kind, cname) in controls:
            safe = cname.replace("\\", "\\\\").replace('"', '\\"')
            lines.append('    {%d, %d, %d, %d, %d, %d, %d, WIN_CTL_%s, "%s"},' % (pi, bx, by, bw, bh, param, seg, kind, safe))
            total += 1
    lines += ["};", "#define WIN_CTL_COUNT ((int)(sizeof WIN_CTL / sizeof WIN_CTL[0]))", "", "#endif", ""]
    open(OUT, "w").write("\n".join(lines))
    print("wrote %s: %d pages, %d controls" % (os.path.relpath(OUT, ROOT), len(pages), total))

if __name__ == "__main__":
    main()
