#!/usr/bin/env python3
"""Turns data/presets.json into src/presets_gen.c (run by `make`)."""
import json, os, sys

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
SRC = os.path.join(ROOT, "data", "presets.json")
OUT = os.path.join(ROOT, "src", "presets_gen.c")

INT = ["key", "scale", "sound", "voicing", "inversion", "octave", "voice_lead", "strum_dir", "arp", "arp_rate", "arp_oct", "vel",
       "pattern", "pat_rate", "smart", "smart_mode", "smart_oct", "melody"]
FLOAT = ["tone", "release", "volume", "strum_ms", "swing", "gate"]

def c_str(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'

def main():
    presets = json.load(open(SRC, encoding="utf-8"))["presets"]
    names = [p["name"] for p in presets]
    if len(set(names)) != len(names):
        sys.exit("duplicate preset names")
    for p in presets:
        if len(p["name"]) > 23:
            sys.exit("preset name too long for the screen: " + p["name"])
    out = ['/* Generated by tools/gen_presets.py from data/presets.json. Do not edit by hand. */',
           '#include "presets.h"', "", "const VcPreset VC_PRESETS[] = {"]
    for p in presets:
        fields = [".name = %s" % c_str(p["name"]), ".genre = %s" % c_str(p["genre"])]
        fields += [".%s = %d" % (k, int(p[k])) for k in INT]
        fields += [".%s = %sf" % (k, repr(float(p[k]))) for k in FLOAT]
        out.append("    {%s}," % ", ".join(fields))
    out += ["};", "const int VC_NUM_PRESETS = (int)(sizeof(VC_PRESETS) / sizeof(VC_PRESETS[0]));", ""]
    open(OUT, "w", encoding="utf-8").write("\n".join(out))
    print("wrote %d presets to %s" % (len(presets), os.path.relpath(OUT, ROOT)))

if __name__ == "__main__":
    main()
