#!/usr/bin/env python3
"""Convert data/songs.json into src/songs_gen.h (compiled into the plugin).

Progression syntax: bars separated by '|'; chords inside a bar split the bar evenly.
  "Am7 | C7 | Fmaj7 | Bm7b5 E7"  ->  Am7 4 beats, C7 4, Fmaj7 4, Bm7b5 2, E7 2
The song data is kept separate from the code so it can be corrected without touching C files.
"""
import json, os, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PCS = {"C": 0, "D": 2, "E": 4, "F": 5, "G": 7, "A": 9, "B": 11}
VALID_STATUS = {"verified", "unverified-analysis", "approximate", "original"}
VALID_CONF = {"high", "medium", "low"}


def pc(name):
    p = PCS[name[0]]
    if len(name) > 1 and name[1] == "#": p += 1
    if len(name) > 1 and name[1] == "b": p -= 1
    return p % 12


def c_str(s):
    if s is None: return "0"
    return '"' + str(s).replace("\\", "\\\\").replace('"', '\\"') + '"'


def expand(prog, beats_per_bar):
    events = []
    for bar in prog.split("|"):
        chords = bar.split()
        if not chords:
            raise ValueError("empty bar in %r" % prog)
        dur = beats_per_bar / len(chords)
        for ch in chords:
            if events and ch == "%":  # repeat previous chord
                ch = events[-1][0]
            events.append((ch, dur))
    return events


def main():
    data = json.load(open(os.path.join(ROOT, "data", "songs.json")))
    songs = sorted(data["songs"], key=lambda s: (s["status"] == "original", s["year"], s["genre"] if s["status"] == "original" else "", s["title"]))  # originals after real songs
    ids = set()
    out = ["/* GENERATED by tools/gen_songs.py from data/songs.json - do not edit */",
           "#include \"songs.h\"", ""]
    for si, s in enumerate(songs):
        assert s["id"] not in ids, "duplicate id " + s["id"]
        ids.add(s["id"])
        assert s["status"] in VALID_STATUS, s["id"]
        assert s["confidence"] in VALID_CONF, s["id"]
        ts = s.get("time_signature")
        num, den = (int(ts.split("/")[0]), int(ts.split("/")[1])) if ts else (4, 4)
        for ci, sec in enumerate(s["sections"]):
            ev = expand(sec["progression"], num * 4.0 / den)
            out.append("static const SongEvent ev_%d_%d[] = {%s};" % (si, ci, ", ".join(
                "{%s, %.4ff}" % (c_str(c), d) for c, d in ev)))
        out.append("static const SongSection sec_%d[] = {%s};" % (si, ", ".join(
            "{%s, ev_%d_%d, %d}" % (c_str(sec["name"]), si, ci, len(expand(sec["progression"], num * 4.0 / den)))
            for ci, sec in enumerate(s["sections"]))))
    out.append("")
    out.append("const Song VC_SONGS[] = {")
    for si, s in enumerate(songs):
        ts = s.get("time_signature")
        num, den = (int(ts.split("/")[0]), int(ts.split("/")[1])) if ts else (4, 4)
        out.append("  {%s, %s, %s, %s, %d, %s, %d, %d, %s, %s, %s, %s, %ff, %s, %d, %d, %d, %s, sec_%d, %d}," % (
            c_str(s["id"]), c_str(s["title"]), c_str(s["artist"]), c_str(s.get("writers")), s["year"],
            c_str(s["key"]), pc(s["key_root"]), 1 if s["minor"] else 0, c_str(s["genre"]),
            c_str(s["status"]), c_str(s["confidence"]), c_str(s.get("recording")),
            float(s["bpm"] or 0), c_str(ts), num, den, 1 if ts else 0, c_str(s.get("notes")), si, len(s["sections"])))
    out.append("};")
    out.append("const int VC_NUM_SONGS = %d;" % len(songs))
    path = os.path.join(ROOT, "src", "songs_gen.c")
    open(path, "w").write("\n".join(out) + "\n")
    print("wrote %s (%d songs, %d sections)" % (path, len(songs), sum(len(s["sections"]) for s in songs)))


if __name__ == "__main__":
    main()
